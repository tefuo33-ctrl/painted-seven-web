function unique(list: string): string[] {
  return [...new Set(list.split(/\s+/).filter(Boolean))];
}

export const MALE_NAMES = unique(MALE);
export const FEMALE_NAMES = unique(FEMALE);

/**
 * Случайные имена для ботов: по одному на каждый пол из списка.
 * В одной игре имена не повторяются; `taken` — имена, которые уже заняты (люди за столом).
 */
export function pickBotNames(genders: Gender[], taken: string[] = [], random: () => number = Math.random): string[] {
  const used = new Set(taken.map((name) => name.trim().toLowerCase()));
  return genders.map((gender) => {
    const pool = (gender === 'male' ? MALE_NAMES : FEMALE_NAMES).filter((name) => !used.has(name.toLowerCase()));
    const name = pool[Math.floor(random() * pool.length)];
    used.add(name.toLowerCase());
    return name;
  });
}
